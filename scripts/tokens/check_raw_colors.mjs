// Hex of 3, 4, 6 or 8 digits. Not part of a longer word, an HTML entity (&#123;) or a
// fragment like #main-content; a 5- or 7-digit run is not a colour.
const HEX = /(?<![\w&])#(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})(?![\w-])/g;
const FUNC = /(?<![\w-])(?:rgba?|hsla?|hwb|oklab|oklch|lab|lch)\s*\(/gi;
const COLOUR_PROP = /(?<![\w-])(color|background|border(?:-(?:top|right|bottom|left))?(?:-color)?|background-color|fill|stroke|outline(?:-color)?)\s*:\s*([^;}\n]*)/gi;
// JS: `el.style.color = 'white'`, `el.style.fill = ...` and the camelCase keys of a style object.
const ASSIGN_PROP = /(?<![\w-])(?:color|fill|stroke)\s*=(?!=)\s*([^;}\n]*)/g;
const CAMEL_PROP = /(?<![\w-])(?:backgroundColor|borderColor|outlineColor)\s*(?:=(?!=)|:)\s*([^;}\n]*)/g;

/**
 * YAML: a `#` starts a comment at a line start or after whitespace, outside quotes.
 * The lines of a block scalar (`key: |` or `>`, indented deeper than the key) are
 * text, not YAML, so a `#` there is css (DeepChat's auxiliaryStyle) and stays.
 */
function stripYamlComments(text) {
  const out = [];
  let scalarIndent = -1; // indent of the key that opened the current block scalar, or -1
  for (const line of text.split('\n')) {
    const indent = line.length - line.trimStart().length;
    if (scalarIndent >= 0) {
      if (line.trim() === '' || indent > scalarIndent) { out.push(line); continue; }
      scalarIndent = -1;
    }
    let kept = line;
    let quote = null;
    for (let i = 0; i < line.length; i++) {
      const c = line[i];
      if (quote) { if (c === quote) quote = null; continue; }
      if (c === '"' || c === "'") { quote = c; continue; }
      if (c === '#' && (i === 0 || /\s/.test(line[i - 1]))) {
        kept = line.slice(0, i) + ' '.repeat(line.length - i);
        break;
      }
    }
    out.push(kept);
    if (/[:-]\s+[|>][+-]?\d*\s*$/.test(kept)) scalarIndent = indent;
  }
  return out.join('\n');
}

/**
 * Replace comments with spaces (newlines kept, so line numbers hold). Strings
 * are tracked so a `//` in a URL or a `#` in a quoted colour is not a comment.
 */
export function stripComments(text, kind) {
  if (kind === 'twig') {
    return text
      .replace(/\{#[\s\S]*?#\}/g, (m) => m.replace(/[^\n]/g, ' '))
      .replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '));
  }
  const blank = (s) => s.replace(/[^\n]/g, ' ');
  if (kind === 'svg') return text.replace(/<!--[\s\S]*?-->/g, (m) => m.replace(/[^\n]/g, ' '));
  if (kind === 'yml') return stripYamlComments(text);
  let out = '';
  let i = 0;
  const n = text.length;
  const lineComments = kind === 'js' || kind === 'php';
  const hashComments = kind === 'php';
  const blockComments = true;
  while (i < n) {
    const c = text[i];
    const next = text[i + 1];
    if (blockComments && c === '/' && next === '*') {
      const end = text.indexOf('*/', i + 2);
      const stop = end === -1 ? n : end + 2;
      out += blank(text.slice(i, stop));
      i = stop;
      continue;
    }
    if (lineComments && c === '/' && next === '/') {
      let stop = text.indexOf('\n', i);
      if (stop === -1) stop = n;
      out += blank(text.slice(i, stop));
      i = stop;
      continue;
    }
    if (hashComments && c === '#' && !(kind === 'php' && next === '[')) {
      let stop = text.indexOf('\n', i);
      if (stop === -1) stop = n;
      out += blank(text.slice(i, stop));
      i = stop;
      continue;
    }
    if (c === '"' || c === "'" || (c === '`' && kind === 'js')) {
      // A string runs to its closing quote; only PHP, and JS template literals, may span lines.
      const spans = kind === 'php' || c === '`';
      let j = i + 1;
      while (j < n) {
        if (text[j] === '\\') { j += 2; continue; }
        if (text[j] === c) { j++; break; }
        if (text[j] === '\n' && !spans) break;
        j++;
      }
      out += text.slice(i, j);
      i = j;
      continue;
    }
    out += c;
    i++;
  }
  return out;
}

/** Colour literals on one comment-stripped line: [{ match }]. */
function findLiterals(line) {
  const hits = [];
  for (const m of line.matchAll(HEX)) hits.push(m[0]);
  for (const m of line.matchAll(FUNC)) hits.push(m[0].replace(/\s+/g, ''));
  const named = (value) => {
    const bare = value.replace(/url\([^)]*\)/gi, ' ').replace(/(["'])(?:\\.|(?!\1).)*\1/g, ' ');
    for (const w of bare.matchAll(/(?<![\w-])[a-zA-Z]+(?![\w-])/g)) {
      if (NAMED.has(w[0].toLowerCase())) hits.push(w[0]);
    }
  };
  // The value of a CSS-style property; quoted names (YAML `color: "white"`, JS) count too.
  for (const m of line.matchAll(COLOUR_PROP)) named(m[2].replace(/(["'])((?:\\.|(?!\1).)*)\1/g, ' $2 '));
  for (const m of line.matchAll(ASSIGN_PROP)) named(m[1].replace(/(["'])((?:\\.|(?!\1).)*)\1/g, ' $2 '));
  for (const m of line.matchAll(CAMEL_PROP)) named(m[1].replace(/(["'])((?:\\.|(?!\1).)*)\1/g, ' $2 '));
  return hits;
}

/** `raw-color-allow: <reason>` on a raw line: the reason text, or '' when there is none. */
function markerReason(rawLine) {
  const m = rawLine.match(/raw-color-allow:(.*)$/);
  if (!m) return null;
  return m[1].replace(/(\*\/|-->|#\}|\?>)\s*$/, '').trim();
}

function scanFile(abs, label, result) {
  const kind = KIND_BY_EXT[abs.split('.').pop()];
  const text = readFileSync(abs, 'utf8');
  const rawLines = text.split('\n');
  if (rawLines.slice(0, 5).some((l) => GENERATED_HEADER.test(l))) {
    result.out.push(`SKIP-GENERATED ${label}`);
    return;
  }
  result.files++;
  const lines = stripComments(text, kind).split('\n');
  lines.forEach((line, idx) => {
    const literals = findLiterals(line);
    const raw = rawLines[idx] ?? '';
    const reason = MARKER.test(raw) ? markerReason(raw) : null;
    if (reason) {
      if (literals.length) result.out.push(`ALLOW ${label}:${idx + 1} ${reason}`);
      return;
    }
    for (const lit of literals) {
      result.hits++;
      result.out.push(`RAW ${label}:${idx + 1} ${lit}${MARKER.test(raw) ? ' (raw-color-allow marker has no reason)' : ''}`);
    }
  });
}

function walk(dir, found = []) {
  for (const name of readdirSync(dir).sort()) {
    if (name === '.git' || name === 'node_modules') continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, found);
    else found.push(p);
  }
  return found;
}

/** Files to scan for one --paths entry: [{ abs, label }]. */
function listFiles(path) {
  const abs = resolve(process.cwd(), path);
  if (!existsSync(abs)) {
    console.error(`${USAGE} (path not found: ${path})`);
    process.exit(2);
  }
  const inRepo = abs === repoRoot || abs.startsWith(repoRoot + sep);
  if (inRepo) {
    const rel = relative(repoRoot, abs) || '.';
    const listed = execFileSync('git', ['ls-files', '-z', '--', rel], { cwd: repoRoot, encoding: 'utf8' });
    return listed.split('\0').filter(Boolean).map((f) => ({ abs: join(repoRoot, f), label: f }));
  }
  const files = statSync(abs).isDirectory() ? walk(abs) : [abs];
  const base = statSync(abs).isDirectory() ? abs : dirname(abs);
  return files.map((f) => ({ abs: f, label: statSync(abs).isDirectory() ? relative(dirname(base), f) || f : f }));
}

function main(argv) {
  let paths = [];
  if (argv.length) {
    if (argv[0] !== '--paths' || argv.length < 2 || argv.slice(1).some((a) => a.startsWith('--'))) {
      console.error(`${USAGE} (bad argument: ${argv.find((a, i) => i === 0 || a.startsWith('--')) ?? ''})`);
      process.exit(2);
    }
    paths = argv.slice(1);
  } else {
    // Against this script's own repo, never the caller's cwd: the swap proof runs the copy in its worktree from wherever it was started.
    paths = [join(repoRoot, DEFAULT_ROOT)];
  }
  const seen = new Set();
  const files = [];
  for (const p of paths) {
    for (const f of listFiles(p)) {
      if (seen.has(f.abs)) continue;
      seen.add(f.abs);
      files.push(f);
    }
  }
  const result = { out: [], hits: 0, files: 0 };
  for (const f of files) {
    const ext = f.abs.split('.').pop();
    if (!Object.hasOwn(KIND_BY_EXT, ext) || !existsSync(f.abs)) continue;
    if (`/${f.label.split(sep).join('/')}`.includes('/tests/fixtures/')) continue;
    scanFile(f.abs, f.label.split(sep).join('/'), result);
  }
  for (const line of result.out) console.log(line);
  console.log(result.hits ? `RESULT: FAIL (${result.hits} hits)` : `RESULT: PASS (${result.files} files)`);
  // process.exitCode, not process.exit(): exit() drops output still queued on a slow pipe (WINDOWS 51).
  process.exitCode = result.hits ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
