#!/usr/bin/env node
/**
 * Raw-colour guard for our Drupal code (22.1-06, DES-01, D-03, D-08).
 *
 * A palette swap is token-only only while no colour lives outside the token
 * source. This script fails on any colour literal in git-tracked css, twig, js,
 * yml, yaml, module, php, inc, install and svg files under html/modules/custom:
 *   - hex colours of 3, 4, 6 or 8 digits;
 *   - rgb(, rgba(, hsl(, hsla(, hwb(, lab(, lch(, oklab(, oklch(;
 *   - a CSS named colour (white, black, rebeccapurple, ...) as the value of a
 *     color, background, border, fill, stroke or outline property (not
 *     transparent, currentColor, inherit, initial, unset, revert, none).
 * Comments are stripped first, so prose about a colour or an issue number
 * ("#2924") in a comment is not a hit.
 *
 * What is skipped, and nothing else:
 *   - a file whose first five lines carry the generator's header
 *     (`GENERATED by scripts/tokens/build_tokens.mjs`); each one is printed as
 *     `SKIP-GENERATED <file>` so a forged header is visible;
 *   - any file under a `tests/fixtures/` directory;
 *   - a line that carries `raw-color-allow: <reason>`: printed as
 *     `ALLOW <file>:<line> <reason>` and not counted. A marker with no reason
 *     is a hit (T-22.1-17). There is no other exemption and no option to add one.
 *     In an svg the marker is an XML comment on the line: `<!-- raw-color-allow: <reason> -->`
 *     (the two brand marks under localnodes_platform/images keep their fixed logo colours this way).
 *
 * Usage:
 *   node scripts/tokens/check_raw_colors.mjs [--paths <file-or-dir>...]
 * Without --paths it scans html/modules/custom of the repo this script lives in, whatever the cwd is. A path inside the repo is read
 * from `git ls-files` (tracked files only); a path outside the repo (the tests'
 * temp dirs) is walked on disk.
 * Output: `RAW <file>:<line> <match>` per hit, `ALLOW ...` per exempted line,
 * then `RESULT: PASS (n files)` or `RESULT: FAIL (n hits)`.
 * Exit 0 pass, 1 any hit, 2 bad usage or an unreadable path. Node built-ins only.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const DEFAULT_ROOT = 'html/modules/custom';
const USAGE = 'usage: check_raw_colors.mjs [--paths <file-or-dir>...]';

const KIND_BY_EXT = {
  css: 'css', twig: 'twig', js: 'js', yml: 'yml', yaml: 'yml',
  module: 'php', php: 'php', inc: 'php', install: 'php', svg: 'svg',
};
const GENERATED_HEADER = /GENERATED by scripts\/tokens\/build_tokens\.mjs/;
const MARKER = /raw-color-allow:/;

