/**
 * Generator target: the socialblue colour scheme (22.1-03, DES-01, D-03, D-08).
 *
 * Renders html/modules/custom/localnodes_platform/config/optional/
 * color.theme.socialblue.yml from `targets.socialblue` in the token source. The
 * install hook _localnodes_platform_apply_brand_palette() reads this file and
 * hands the palette to drupal/color, which recolours socialblue's brand.css by
 * find-and-replace of each stock hex.
 *
 * Guards (22.1-RESEARCH Pitfall 2, Anti-Patterns), each proven by a test in
 * scripts/tokens/tests/build_tokens.test.mjs:
 *   - exactly the 15 fields of socialblue/color/color.inc;
 *   - all 15 values distinct (drupal/color can't tell two equal values apart);
 *   - the 15 values must not equal socialblue's stock scheme, because
 *     color_scheme_form_submit() then DELETES color.theme.socialblue and
 *     returns, and the install hook would rewrite the palette on every run.
 */
import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { TokenError, headerLines } from '../lib/tokens.mjs';

export const id = 'socialblue';
export const label = 'socialblue scheme';

export const path = (repoRoot) => resolve(repoRoot, 'html/modules/custom/localnodes_platform/config/optional/color.theme.socialblue.yml');

// socialblue/color/color.inc, 'fields', in that order.
export const FIELDS = [
  'brand-primary',
  'brand-secondary',
  'brand-accent',
  'brand-accent-text',
  'brand-link',
  'navbar-bg',
  'navbar-text',
  'navbar-active-bg',
  'navbar-active-text',
  'navbar-sec-bg',
  'navbar-sec-text',
  'second-line-navbar-bg',
  'second-line-navbar-text',
  'second-line-navbar-active-bg',
  'second-line-navbar-active-text',
];

const FIXTURE = resolve(dirname(fileURLToPath(import.meta.url)), '../fixtures/stock-socialblue.json');

/** The 15 fields, validated, in color.inc order: [[field, hex], ...]. */
export function schemeFields(resolved) {
  const scheme = resolved?.targets?.socialblue ?? {};
  const names = Object.keys(scheme);
  if (names.length !== FIELDS.length) {
    const missing = FIELDS.filter((f) => !names.includes(f));
    throw new TokenError(
      `socialblue target has ${names.length} of ${FIELDS.length} fields`
      + `${missing.length ? ` (missing: ${missing.join(', ')})` : ''}; drupal/color needs all ${FIELDS.length}`,
    );
  }
  const unknown = names.filter((n) => !FIELDS.includes(n));
  if (unknown.length) throw new TokenError(`socialblue target has fields color.inc doesn't know: ${unknown.join(', ')}`);
  for (const f of FIELDS) {
    if (!/^#[0-9a-f]{6}$/.test(scheme[f])) throw new TokenError(`targets.socialblue.${f} resolves to "${scheme[f]}", not a 6-digit hex`);
  }
  const seen = new Map();
  for (const f of FIELDS) {
    if (seen.has(scheme[f])) {
      throw new TokenError(
        `socialblue fields ${seen.get(scheme[f])} and ${f} both resolve to ${scheme[f]}; `
        + 'the 15 values must be distinct (color.inc: drupal/color replaces by value)',
      );
    }
    seen.set(scheme[f], f);
  }
  const stock = JSON.parse(readFileSync(FIXTURE, 'utf8')).targets.socialblue;
  if (FIELDS.every((f) => scheme[f] === stock[f])) {
    throw new TokenError(
      'the 15 socialblue values equal socialblue\'s stock scheme; drupal/color would delete '
      + 'color.theme.socialblue (color_scheme_form_submit) and the brand would silently revert to stock',
    );
  }
  return FIELDS.map((f) => [f, scheme[f]]);
}

export function render(resolved) {
  const fields = schemeFields(resolved);
  const header = [
    ...headerLines(),
    '',
    'LocalNodes brand palette for the socialblue colour scheme (DES-01, D-03).',
    'All 15 values are distinct and differ from stock, as drupal/color needs.',
    'Shipped in config/optional so a color.theme.socialblue written earlier in the',
    'install can never cause a pre-existing-config failure. The stylesheets are',
    'generated by _localnodes_platform_apply_brand_palette() in',
    'localnodes_platform.install, which reads this file; drupal/color only',
    'generates CSS from its form submit handler, never on config import.',
    'scripts/check_token_parity.mjs runs --check for this file.',
  ].map((l) => (l === '' ? '#' : `# ${l}`));
  return [
    ...header,
    'palette:',
    ...fields.map(([f, v]) => `  ${f}: '${v}'`),
    'stylesheets: []',
    'files: []',
    '',
  ].join('\n');
}
